#include "operacao_Basica.h"

double adicao(double a, double b) {
    return a + b;
}

double subtracao(double a, double b) {
    return a - b;
}

double multiplicacao(double a, double b) {
    return a * b;
}

double divisao(double a, double b) {
    return a / b;
}
double porcentagem(double a, double b) {
    return (a * b) / 100;
}